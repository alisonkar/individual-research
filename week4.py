def set_seed(seed=42):

    random.seed(seed)
    np.random.seed(seed)

    torch.manual_seed(seed)

    if torch.cuda.is_available():
        torch.cuda.manual_seed_all(seed)


# ------------------------------------------------------------
# 3. PSNR
# ------------------------------------------------------------

def calc_psnr(pred, target):

    pred = torch.clamp(
        pred,
        0.0,
        1.0
    )

    target = torch.clamp(
        target,
        0.0,
        1.0
    )

    mse = torch.mean(
        (pred - target) ** 2,
        dim=(1, 2, 3)
    )

    psnr = 10.0 * torch.log10(
        1.0 / (mse + 1e-10)
    )

    return psnr


# ------------------------------------------------------------
# 4. Validation
# ------------------------------------------------------------

@torch.no_grad()
def validate_model(
    model,
    loader,
    device
):

    model.eval()

    psnr_values = []

    for batch in loader:

        x = batch["input"].to(device)
        y = batch["target"].to(device)
        e = batch["exposure"].to(device)

        pred = model(
            x,
            e
        )

        psnr = calc_psnr(
            pred,
            y
        )

        psnr_values.extend(
            psnr.cpu().tolist()
        )

    return float(
        np.mean(psnr_values)
    )


# ------------------------------------------------------------
# 5. 공통 training 함수
# ------------------------------------------------------------

def train_model(
    model,
    model_name,
    train_loader,
    val_loader,
    device,
    num_iter=5000,
    lr=1e-4,
    val_interval=100
):

    print("\n" + "=" * 75)
    print(f"Training : {model_name}")
    print("=" * 75)

    model = model.to(device)

    criterion = nn.L1Loss()

    optimizer = optim.Adam(
        model.parameters(),
        lr=lr
    )

    # --------------------------------------------
    # History
    # --------------------------------------------

    train_history = []

    val_steps = []
    val_history = []

    best_psnr = -float("inf")
    best_step = 0

    save_path = os.path.join(
        WEEK4_RESULT_DIR,
        f"{model_name}_best.pt"
    )

    # DataLoader를 계속 순환시키기 위한 iterator
    train_iter = iter(train_loader)


    # --------------------------------------------
    # Training
    # --------------------------------------------

    for step in range(
        1,
        num_iter + 1
    ):

        model.train()

        # ----------------------------------------
        # batch 가져오기
        # 끝까지 갔으면 새 epoch 시작
        # ----------------------------------------

        try:

            batch = next(train_iter)

        except StopIteration:

            train_iter = iter(train_loader)
            batch = next(train_iter)


        x = batch["input"].to(device)
        y = batch["target"].to(device)
        e = batch["exposure"].to(device)


        # ----------------------------------------
        # Forward
        # ----------------------------------------

        pred = model(
            x,
            e
        )


        # ----------------------------------------
        # Loss
        # ----------------------------------------

        loss = criterion(
            pred,
            y
        )


        # ----------------------------------------
        # Backpropagation
        # ----------------------------------------

        optimizer.zero_grad()

        loss.backward()

        optimizer.step()


        train_history.append(
            float(loss.item())
        )


        # ----------------------------------------
        # Validation
        # ----------------------------------------

        if (
            step == 1
            or step % val_interval == 0
            or step == num_iter
        ):

            val_psnr = validate_model(
                model,
                val_loader,
                device
            )

            val_steps.append(step)
            val_history.append(val_psnr)


            print(
                f"[{model_name}] "
                f"Step {step:4d}/{num_iter} | "
                f"L1={loss.item():.6f} | "
                f"Val PSNR={val_psnr:.4f} dB"
            )


            # ------------------------------------
            # Best checkpoint
            # ------------------------------------

            if val_psnr > best_psnr:

                best_psnr = val_psnr
                best_step = step

                torch.save(
                    {
                        "model_state_dict":
                            model.state_dict(),

                        "step":
                            step,

                        "val_psnr":
                            val_psnr,

                        "model_name":
                            model_name
                    },
                    save_path
                )


    # --------------------------------------------------------
    # 학습 완료
    # --------------------------------------------------------

    print("\nTraining finished.")

    print(
        f"Best validation PSNR : "
        f"{best_psnr:.4f} dB"
    )

    print(
        f"Best step            : "
        f"{best_step}"
    )

    print(
        f"Checkpoint           : "
        f"{save_path}"
    )

    print("=" * 75)


    return {
        "model": model,

        "train_loss":
            train_history,

        "val_steps":
            val_steps,

        "val_psnr":
            val_history,

        "best_psnr":
            best_psnr,

        "best_step":
            best_step,

        "checkpoint":
            save_path
    }

