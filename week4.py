# ------------------------------------------------------------
# 1. Week 3에서 사용한 exposure 설정
# ------------------------------------------------------------

EXPOSURES = [3, 7, 11, 15, 19]

MOTION_ANGLE = 45.0

# Gaussian noise
NOISE_SIGMA = 5 / 255.0


# ------------------------------------------------------------
# 2. Motion blur kernel 생성
# ------------------------------------------------------------

def make_motion_kernel(length, angle=45.0):

    # kernel size는 홀수로 맞춤
    length = int(round(length))

    if length % 2 == 0:
        length += 1

    length = max(length, 1)

    kernel = np.zeros((length, length), dtype=np.float32)

    center = length // 2

    # 가운데에 수평선 생성
    kernel[center, :] = 1.0

    # 원하는 angle로 회전
    rotation_matrix = cv2.getRotationMatrix2D(
        (center, center),
        angle,
        1.0
    )

    kernel = cv2.warpAffine(
        kernel,
        rotation_matrix,
        (length, length)
    )

    kernel /= (kernel.sum() + 1e-8)

    return kernel


# ------------------------------------------------------------
# 3. Exposure -> Blur length
# ------------------------------------------------------------

def exposure_to_blur_length(exposure):
    """
    Week 3에서 확인한 설정:
    exposure가 커질수록 motion blur가 강해짐.

    exposure = 3  -> length 3
    exposure = 7  -> length 7
    exposure = 11 -> length 11
    exposure = 15 -> length 15
    exposure = 19 -> length 19
    """
    return int(exposure)


# ------------------------------------------------------------
# 4. Week 4 degradation 함수
# ------------------------------------------------------------

def degrade_image(
    hr_tensor,
    exposure,
    noise_on=True,
    noise_sigma=NOISE_SIGMA,
    scale=2
):
    """
    Input
    -----
    hr_tensor : [C,H,W], range [0,1]
    exposure  : exposure condition

    Pipeline
    --------
    HR
      -> exposure-dependent motion blur
      -> downsample
      -> bicubic upsample
      -> optional Gaussian noise
    """

    # [C,H,W] -> [H,W,C]
    img = hr_tensor.permute(1, 2, 0).cpu().numpy()

    # -----------------------------------------
    # Exposure-dependent motion blur
    # -----------------------------------------

    blur_length = exposure_to_blur_length(exposure)

    kernel = make_motion_kernel(
        blur_length,
        MOTION_ANGLE
    )

    blurred = cv2.filter2D(
        img,
        -1,
        kernel,
        borderType=cv2.BORDER_REFLECT
    )

    h, w = blurred.shape[:2]

    # -----------------------------------------
    # Downsample
    # -----------------------------------------

    lr = cv2.resize(
        blurred,
        (w // scale, h // scale),
        interpolation=cv2.INTER_AREA
    )

    # -----------------------------------------
    # Bicubic upsample
    # -----------------------------------------

    degraded = cv2.resize(
        lr,
        (w, h),
        interpolation=cv2.INTER_CUBIC
    )

    # -----------------------------------------
    # Optional Gaussian noise
    # -----------------------------------------

    if noise_on:

        noise = np.random.normal(
            0.0,
            noise_sigma,
            degraded.shape
        ).astype(np.float32)

        degraded = degraded + noise

    degraded = np.clip(
        degraded,
        0.0,
        1.0
    ).astype(np.float32)

    degraded_tensor = torch.from_numpy(
        degraded
    ).permute(2, 0, 1)

    return degraded_tensor


