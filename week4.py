from torchvision.transforms.functional import to_tensor


# ------------------------------------------------------------
# 1. 기본 설정
# ------------------------------------------------------------

PATCH_SIZE = 48
BATCH_SIZE = 8
#이게 중요한 이유는 Week 4의 핵심이 "patch size를 바꿨더니 성능이 달라졌다"가 아니라,
#동일한 SRCNN 학습 조건에서 exposure 정보를 주면 복원이 좋아지는가?
#를 비교하는 것이기 때문이다!그래서 기존 조건을 고정함!(patch size)


# ------------------------------------------------------------
# 2. Week 4 Dataset
# ------------------------------------------------------------

class Week4ExposureDataset(Dataset):

    def __init__(
        self,
        hr_dir,
        file_list,
        exposures,
        patch_size=48,
        training=False,
        noise_on=True
    ):

        self.hr_dir = hr_dir
        self.file_list = list(file_list)
        self.exposures = list(exposures)

        self.patch_size = patch_size
        self.training = training
        self.noise_on = noise_on

        # ----------------------------------------------------
        # 각 image × exposure 조합을 하나의 sample로 구성
        #
        # 예:
        # image_01 × exposure 3
        # image_01 × exposure 7
        # ...
        # image_02 × exposure 3
        # ...
        # ----------------------------------------------------

        self.samples = []

        for filename in self.file_list:
            for exposure in self.exposures:

                self.samples.append(
                    (filename, exposure)
                )


    def __len__(self):

        return len(self.samples)


    def _crop(self, img_tensor):

        _, h, w = img_tensor.shape

        ps = self.patch_size

        if h < ps or w < ps:
            raise ValueError(
                f"Image size ({h},{w}) is smaller "
                f"than PATCH_SIZE={ps}"
            )

        # --------------------------------------------
        # Train:
        # random crop
        # --------------------------------------------

        if self.training:

            top = random.randint(
                0,
                h - ps
            )

            left = random.randint(
                0,
                w - ps
            )

        # --------------------------------------------
        # Validation / Test:
        # center crop
        #
        # 매 평가마다 정확히 같은 영역을 사용
        # --------------------------------------------

        else:

            top = (h - ps) // 2
            left = (w - ps) // 2


        crop = img_tensor[
            :,
            top:top + ps,
            left:left + ps
        ]

        return crop


    def __getitem__(self, idx):

        filename, exposure = self.samples[idx]

        # --------------------------------------------
        # HR image load
        # --------------------------------------------

        path = os.path.join(
            self.hr_dir,
            filename
        )

        img = Image.open(path).convert("RGB")

        hr = to_tensor(img)

        # --------------------------------------------
        # Crop
        # --------------------------------------------

        hr = self._crop(hr)


        # --------------------------------------------
        # Degradation
        #
        # HR
        # -> exposure-dependent blur
        # -> downsample
        # -> bicubic upsample
        # -> optional noise
        # --------------------------------------------

        degraded = degrade_image(
            hr,
            exposure=exposure,
            noise_on=self.noise_on
        )


        # --------------------------------------------
        # Exposure conditioning value
        # --------------------------------------------

        exposure_norm = torch.tensor(
            normalize_exposure(exposure),
            dtype=torch.float32
        )


        return {
            "input": degraded,
            "target": hr,
            "exposure": exposure_norm,
            "exposure_raw": torch.tensor(
                exposure,
                dtype=torch.float32
            ),
            "filename": filename
        }


