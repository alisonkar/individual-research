import torch
import torch.nn as nn
import torch.nn.functional as F


# ------------------------------------------------------------
# 1. Baseline: SRCNN-no-exp
# ------------------------------------------------------------
# exposure 정보를 전혀 사용하지 않음
#
# Input:
#   degraded RGB image [B, 3, H, W]
#
# Network:
#   3 -> 64 -> 32 -> 3
# ------------------------------------------------------------

class SRCNNNoExposure(nn.Module):

    def __init__(self):
        super().__init__()

        self.conv1 = nn.Conv2d(
            3, 64,
            kernel_size=9,
            padding=4
        )

        self.conv2 = nn.Conv2d(
            64, 32,
            kernel_size=5,
            padding=2
        )

        self.conv3 = nn.Conv2d(
            32, 3,
            kernel_size=5,
            padding=2
        )


    def forward(self, x, exposure=None):

        x = F.relu(self.conv1(x))
        x = F.relu(self.conv2(x))
        x = self.conv3(x)

        return x


# ------------------------------------------------------------
# 2. SRCNN-concat
# ------------------------------------------------------------
# exposure 값을 하나의 추가 channel로 만들어
# RGB image 뒤에 붙임.
#
# RGB          : 3 channels
# Exposure map : 1 channel
# -------------------------
# Input        : 4 channels
#
# 예:
# exposure normalized = 0.5
#
# exposure map 전체가
#
# [0.5 0.5 0.5 ...]
# [0.5 0.5 0.5 ...]
# [0.5 0.5 0.5 ...]
#
# 로 구성됨.
# ------------------------------------------------------------

class SRCNNConcat(nn.Module):

    def __init__(self):
        super().__init__()

        self.conv1 = nn.Conv2d(
            4, 64,
            kernel_size=9,
            padding=4
        )

        self.conv2 = nn.Conv2d(
            64, 32,
            kernel_size=5,
            padding=2
        )

        self.conv3 = nn.Conv2d(
            32, 3,
            kernel_size=5,
            padding=2
        )


    def forward(self, x, exposure):

        B, _, H, W = x.shape

        # [B] -> [B,1,1,1]
        e = exposure.view(B, 1, 1, 1)

        # spatial exposure map
        e_map = e.expand(
            B, 1, H, W
        )

        # RGB + exposure
        x = torch.cat(
            [x, e_map],
            dim=1
        )

        x = F.relu(self.conv1(x))
        x = F.relu(self.conv2(x))
        x = self.conv3(x)

        return x


# ------------------------------------------------------------
# 3. FiLM layer
# ------------------------------------------------------------
#
# FiLM:
#
#       feature'
#          =
# gamma(exposure) * feature
#          +
# beta(exposure)
#
# exposure에 따라 각 feature channel을
# scale / shift 함.
# ------------------------------------------------------------

class FiLMLayer(nn.Module):

    def __init__(
        self,
        num_channels,
        hidden_dim=32
    ):
        super().__init__()

        self.mlp = nn.Sequential(

            nn.Linear(
                1,
                hidden_dim
            ),

            nn.ReLU(),

            nn.Linear(
                hidden_dim,
                2 * num_channels
            )
        )


    def forward(
        self,
        feature,
        exposure
    ):

        B = feature.shape[0]

        # [B] -> [B,1]
        e = exposure.view(B, 1)

        params = self.mlp(e)

        gamma, beta = torch.chunk(
            params,
            2,
            dim=1
        )

        # [B,C] -> [B,C,1,1]
        gamma = gamma.view(
            B, -1, 1, 1
        )

        beta = beta.view(
            B, -1, 1, 1
        )

        # identity-centered modulation
        feature = (
            (1.0 + gamma) * feature
            + beta
        )

        return feature


# ------------------------------------------------------------
# 4. FiLM-SRCNN
# ------------------------------------------------------------
#
# degraded image
#       |
#     Conv1
#       |
#     FiLM1  <- exposure
#       |
#     Conv2
#       |
#     FiLM2  <- exposure
#       |
#     Conv3
#       |
#   Restored image
# ------------------------------------------------------------

class FiLMSRCNN(nn.Module):

    def __init__(self):
        super().__init__()

        self.conv1 = nn.Conv2d(
            3, 64,
            kernel_size=9,
            padding=4
        )

        self.film1 = FiLMLayer(
            num_channels=64
        )

        self.conv2 = nn.Conv2d(
            64, 32,
            kernel_size=5,
            padding=2
        )

        self.film2 = FiLMLayer(
            num_channels=32
        )

        self.conv3 = nn.Conv2d(
            32, 3,
            kernel_size=5,
            padding=2
        )


    def forward(
        self,
        x,
        exposure
    ):

        # Conv 1
        x = self.conv1(x)

        # Exposure-dependent modulation
        x = self.film1(
            x,
            exposure
        )

        x = F.relu(x)


        # Conv 2
        x = self.conv2(x)

        # Exposure-dependent modulation
        x = self.film2(
            x,
            exposure
        )

        x = F.relu(x)


        # reconstruction
        x = self.conv3(x)

        return x


