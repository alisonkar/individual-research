def calc_ssim_batch(pred, target):

    pred = torch.clamp(pred, 0.0, 1.0)
    target = torch.clamp(target, 0.0, 1.0)

    pred_np = pred.detach().cpu().numpy()
    target_np = target.detach().cpu().numpy()

    values = []

    for i in range(pred_np.shape[0]):

        # CHW -> HWC
        p = np.transpose(
            pred_np[i],
            (1, 2, 0)
        )

        t = np.transpose(
            target_np[i],
            (1, 2, 0)
        )

        value = skimage_ssim(
            t,
            p,
            data_range=1.0,
            channel_axis=2
        )

        values.append(value)

    return values


