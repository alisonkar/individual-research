@torch.no_grad()
def evaluate_model(model, loader, device):

    model.eval()

    all_psnr = []
    all_ssim = []

    for batch in loader:

        x = batch["input"].to(device)
        y = batch["target"].to(device)
        e = batch["exposure"].to(device)

        pred = model(
            x,
            e
        )

        # PSNR
        psnr = calc_psnr(
            pred,
            y
        )

        all_psnr.extend(
            psnr.cpu().tolist()
        )

        # SSIM
        ssim = calc_ssim_batch(
            pred,
            y
        )

        all_ssim.extend(ssim)

    return {
        "psnr": float(np.mean(all_psnr)),
        "ssim": float(np.mean(all_ssim))
    }


